import io
from datetime import date
from decimal import Decimal

from django.utils import timezone
from django.conf import settings

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.platypus import (
    SimpleDocTemplate, Table, TableStyle, Paragraph, Spacer,
    HRFlowable, Image as RLImage
)

import qrcode


# Brand colors
NAVY = colors.HexColor('#0D1B2A')
TEAL = colors.HexColor('#00B4A6')
AMBER = colors.HexColor('#F5A623')
LIGHT_GRAY = colors.HexColor('#F8F9FA')
MED_GRAY = colors.HexColor('#6C757D')
WHITE = colors.white


def _make_qr_image(url, size_mm=25):
    """Generate QR code as ReportLab-compatible image."""
    qr = qrcode.QRCode(version=1, error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=8, border=2)
    qr.add_data(url)
    qr.make(fit=True)
    img = qr.make_image(fill_color='black', back_color='white')
    buf = io.BytesIO()
    img.save(buf, format='PNG')
    buf.seek(0)
    return RLImage(buf, width=size_mm * mm, height=size_mm * mm)


def generate_pdf(report_record, report_data):
    """
    Generate a professional PDF report.
    Returns bytes of the PDF.
    """
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4,
        rightMargin=15 * mm, leftMargin=15 * mm,
        topMargin=15 * mm, bottomMargin=20 * mm
    )

    styles = getSampleStyleSheet()
    story = []

    # ─── HEADER ──────────────────────────────────────────────────────────────
    header_style = ParagraphStyle('Header', fontName='Helvetica-Bold', fontSize=22, textColor=NAVY, spaceAfter=2)
    sub_style = ParagraphStyle('Sub', fontName='Helvetica', fontSize=9, textColor=MED_GRAY)
    title_style = ParagraphStyle('Title', fontName='Helvetica-Bold', fontSize=14, textColor=TEAL, spaceBefore=8, spaceAfter=4)
    normal_style = ParagraphStyle('Normal2', fontName='Helvetica', fontSize=9, textColor=NAVY)
    small_style = ParagraphStyle('Small', fontName='Helvetica', fontSize=8, textColor=MED_GRAY)

    story.append(Paragraph('Sanalogx', header_style))
    story.append(Paragraph('Hospital Pharmacy Stock Optimization', sub_style))
    story.append(HRFlowable(width='100%', thickness=2, color=TEAL, spaceAfter=8))

    # Meta table
    date_from_str = report_record.date_from.strftime('%d %b %Y') if report_record.date_from else 'All Time'
    date_to_str = report_record.date_to.strftime('%d %b %Y') if report_record.date_to else 'Present'
    generated_by = report_record.generated_by.get_full_name() or report_record.generated_by.username if report_record.generated_by else 'System'

    meta_data = [
        ['Report:', report_record.get_report_type_display()],
        ['Report ID:', report_record.report_id],
        ['Period:', f"{date_from_str} — {date_to_str}"],
        ['Generated:', report_record.generated_at.strftime('%d %b %Y %H:%M UTC') if report_record.generated_at else timezone.now().strftime('%d %b %Y %H:%M UTC')],
        ['Generated By:', generated_by],
    ]
    meta_table = Table(meta_data, colWidths=[35 * mm, 130 * mm])
    meta_table.setStyle(TableStyle([
        ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
        ('FONTNAME', (1, 0), (1, -1), 'Helvetica'),
        ('FONTSIZE', (0, 0), (-1, -1), 9),
        ('TEXTCOLOR', (0, 0), (0, -1), MED_GRAY),
        ('TEXTCOLOR', (1, 0), (1, -1), NAVY),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
    ]))
    story.append(meta_table)
    story.append(HRFlowable(width='100%', thickness=0.5, color=LIGHT_GRAY, spaceBefore=8, spaceAfter=8))

    # ─── SUMMARY ─────────────────────────────────────────────────────────────
    summary = report_data.get('summary', {})
    if summary:
        story.append(Paragraph('SUMMARY', title_style))
        summ_items = list(summary.items())
        col_count = min(4, len(summ_items))
        row_data = []
        for i in range(0, len(summ_items), col_count):
            chunk = summ_items[i:i + col_count]
            labels = [k.replace('_', ' ').upper() for k, v in chunk]
            values = [str(v) for k, v in chunk]
            while len(labels) < col_count:
                labels.append('')
                values.append('')
            row_data.append(labels)
            row_data.append(values)

        col_w = 170 * mm / col_count
        summ_table = Table(row_data, colWidths=[col_w] * col_count)
        summ_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), LIGHT_GRAY),
            ('FONTNAME', (0, 0), (-1, -1), 'Helvetica'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 8),
            ('TEXTCOLOR', (0, 0), (-1, 0), MED_GRAY),
            ('TEXTCOLOR', (0, 1), (-1, -1), NAVY),
            ('FONTSIZE', (0, 1), (-1, 1), 12),
            ('FONTNAME', (0, 1), (-1, 1), 'Helvetica-Bold'),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('ROWBACKGROUNDS', (0, 0), (-1, -1), [LIGHT_GRAY, WHITE]),
            ('BOX', (0, 0), (-1, -1), 0.5, TEAL),
            ('INNERGRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#DEE2E6')),
        ]))
        story.append(summ_table)
        story.append(Spacer(1, 6 * mm))

    # ─── DATA TABLE ──────────────────────────────────────────────────────────
    data_rows = report_data.get('data', [])
    columns = report_data.get('columns', [])

    if data_rows and columns:
        story.append(Paragraph('REPORT DATA', title_style))

        table_data = [columns]
        for row in data_rows[:500]:
            if isinstance(row, dict):
                table_data.append([str(v) for v in row.values()])
            else:
                table_data.append([str(v) for v in row])

        col_w = 170 * mm / len(columns)
        data_table = Table(table_data, colWidths=[col_w] * len(columns), repeatRows=1)
        data_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), NAVY),
            ('TEXTCOLOR', (0, 0), (-1, 0), WHITE),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 7),
            ('FONTSIZE', (0, 1), (-1, -1), 7),
            ('FONTNAME', (0, 1), (-1, -1), 'Helvetica'),
            ('TEXTCOLOR', (0, 1), (-1, -1), NAVY),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [WHITE, LIGHT_GRAY]),
            ('INNERGRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#DEE2E6')),
            ('BOX', (0, 0), (-1, -1), 0.5, TEAL),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ]))
        story.append(data_table)
        story.append(Spacer(1, 6 * mm))

        if len(data_rows) > 500:
            story.append(Paragraph(f'Note: Showing first 500 of {len(data_rows)} records. Download CSV for full dataset.', small_style))
    else:
        story.append(Paragraph('No records found for the selected period and filters.', normal_style))

    # ─── FOOTER + QR ─────────────────────────────────────────────────────────
    story.append(HRFlowable(width='100%', thickness=0.5, color=TEAL, spaceBefore=6))

    verify_url = report_record.get_verification_url()
    qr_img = _make_qr_image(verify_url, size_mm=28)

    footer_data = [
        [
            Paragraph(f'Generated by Sanalogx · Report ID: {report_record.report_id}', small_style),
            Paragraph('Scan QR to verify report authenticity', small_style),
            qr_img,
        ],
    ]
    footer_table = Table(footer_data, colWidths=[100 * mm, 42 * mm, 30 * mm])
    footer_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('ALIGN', (2, 0), (2, 0), 'RIGHT'),
    ]))
    story.append(footer_table)

    doc.build(story)
    buf.seek(0)
    return buf.read()
