"""
reports/excel_service.py
Phase 7 — Professional Excel Report Generator using openpyxl
"""

import io
from openpyxl import Workbook
from openpyxl.styles import (
    Font, PatternFill, Alignment, Border, Side
)
from openpyxl.utils import get_column_letter


NAVY_HEX = '0D1B2A'
TEAL_HEX = '00B4A6'
LIGHT_GRAY_HEX = 'F8F9FA'


def _header_fill(hex_color):
    return PatternFill(start_color=hex_color, end_color=hex_color, fill_type='solid')


def _border():
    thin = Side(style='thin', color='DEE2E6')
    return Border(left=thin, right=thin, top=thin, bottom=thin)


def generate_excel(report_record, report_data):
    """
    Generate a professional Excel file with Summary + Data sheets.
    Returns bytes of the Excel workbook.
    """
    wb = Workbook()

    # ─── SHEET 1: Summary ────────────────────────────────────────────────────
    ws_summary = wb.active
    ws_summary.title = 'Summary'

    # Title block
    ws_summary['A1'] = 'Sanalogx — Hospital Pharmacy Stock Optimization'
    ws_summary['A1'].font = Font(name='Calibri', bold=True, size=16, color=NAVY_HEX)
    ws_summary.merge_cells('A1:E1')

    ws_summary['A2'] = report_record.get_report_type_display()
    ws_summary['A2'].font = Font(name='Calibri', bold=True, size=13, color=TEAL_HEX)
    ws_summary.merge_cells('A2:E2')

    date_from_str = report_record.date_from.strftime('%d %b %Y') if report_record.date_from else 'All Time'
    date_to_str = report_record.date_to.strftime('%d %b %Y') if report_record.date_to else 'Present'
    meta_rows = [
        ['Report ID:', report_record.report_id],
        ['Period:', f"{date_from_str} — {date_to_str}"],
        ['Generated:', report_record.generated_at.strftime('%d %b %Y %H:%M UTC') if report_record.generated_at else ''],
        ['Generated By:', report_record.generated_by.get_full_name() if report_record.generated_by else 'System'],
    ]
    for i, row in enumerate(meta_rows, start=4):
        ws_summary[f'A{i}'] = row[0]
        ws_summary[f'A{i}'].font = Font(bold=True, color='6C757D')
        ws_summary[f'B{i}'] = row[1]
        ws_summary[f'B{i}'].font = Font(color=NAVY_HEX)

    # Summary KPIs
    summary = report_data.get('summary', {})
    if summary:
        ws_summary['A9'] = 'SUMMARY KPIs'
        ws_summary['A9'].font = Font(bold=True, size=11, color='FFFFFF')
        ws_summary['A9'].fill = _header_fill(TEAL_HEX)
        ws_summary.merge_cells('A9:B9')

        for j, (key, val) in enumerate(summary.items(), start=10):
            ws_summary[f'A{j}'] = key.replace('_', ' ').title()
            ws_summary[f'A{j}'].font = Font(bold=True, color='6C757D')
            ws_summary[f'B{j}'] = val
            ws_summary[f'B{j}'].font = Font(bold=True, size=12, color=NAVY_HEX)
            if j % 2 == 0:
                ws_summary[f'A{j}'].fill = _header_fill(LIGHT_GRAY_HEX)
                ws_summary[f'B{j}'].fill = _header_fill(LIGHT_GRAY_HEX)

    ws_summary.column_dimensions['A'].width = 28
    ws_summary.column_dimensions['B'].width = 30

    # ─── SHEET 2: Report Data ────────────────────────────────────────────────
    ws_data = wb.create_sheet(title='Report Data')
    columns = report_data.get('columns', [])
    data_rows = report_data.get('data', [])

    if columns:
        # Header row
        for col_idx, col_name in enumerate(columns, start=1):
            cell = ws_data.cell(row=1, column=col_idx, value=col_name)
            cell.font = Font(name='Calibri', bold=True, color='FFFFFF', size=10)
            cell.fill = _header_fill(NAVY_HEX)
            cell.alignment = Alignment(horizontal='center', vertical='center')
            cell.border = _border()

        # Data rows
        for row_idx, row in enumerate(data_rows, start=2):
            values = list(row.values()) if isinstance(row, dict) else list(row)
            for col_idx, val in enumerate(values, start=1):
                cell = ws_data.cell(row=row_idx, column=col_idx, value=val)
                cell.font = Font(name='Calibri', size=9)
                cell.border = _border()
                cell.alignment = Alignment(vertical='center')
                if row_idx % 2 == 0:
                    cell.fill = _header_fill(LIGHT_GRAY_HEX)

        # Auto-size columns
        for col_idx in range(1, len(columns) + 1):
            col_letter = get_column_letter(col_idx)
            max_len = max(
                len(str(ws_data.cell(row=r, column=col_idx).value or ''))
                for r in range(1, min(len(data_rows) + 2, 100))
            )
            ws_data.column_dimensions[col_letter].width = min(max(max_len + 2, 12), 40)

        ws_data.freeze_panes = 'A2'

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf.read()
